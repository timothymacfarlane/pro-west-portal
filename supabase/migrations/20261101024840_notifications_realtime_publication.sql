-- The bell already subscribes to notification inserts and updates. Publish the
-- table so those changes can reach signed-in users under its existing RLS.
do $$
begin
  if not exists (
    select 1
    from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'notifications'
  ) then
    alter publication supabase_realtime add table public.notifications;
  end if;
end $$;
